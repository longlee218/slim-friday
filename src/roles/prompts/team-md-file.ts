import { mkdirSync, renameSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { workspacePaths } from "../../config/workspace-paths";
import { buildTeamMd } from "./team-md";

/** First lines of the file: it is a snapshot, and says what is and is not live. */
const HEADER = `<!-- Generated by Friday at every start from the role registry and the caps in code. Edits are overwritten.
     The lead's prompt rebuilds this text for every run and adds the channel's locations: the lead reads no file, so
     changing this file changes nothing. To change the team, change the role data. -->

`;

/**
 * Write `<AGENT_HOME>/TEAM.md`: the roster and caps the lead sees, so the owner can read the team the code defines.
 * Atomic (temp file, then rename). The locations section is a note, because locations belong to a channel. Returns the path.
 */
export function writeTeamFile(agentHome: string): string {
  const file = workspacePaths(agentHome).team;
  mkdirSync(dirname(file), { recursive: true });
  const text = `${HEADER}${buildTeamMd({
    locationsNote: "- per channel: the lead's prompt lists the locations linked to the channel",
  })}\n`;
  const tmp = `${file}.tmp`;
  writeFileSync(tmp, text);
  renameSync(tmp, file);
  return file;
}
