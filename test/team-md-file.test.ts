import { expect, test } from "bun:test";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { writeTeamFile } from "../src/roles/prompts/team-md-file";
import { makeEnv } from "./helpers";

/* TEAM.md in AGENT_HOME: a generated snapshot of the roster, rewritten at every start. */

test("writeTeamFile writes the roster with a header and no channel locations, and rewrites on edit", () => {
  const env = makeEnv();
  const file = writeTeamFile(env.home);
  expect(file).toBe(join(env.home, "TEAM.md"));
  const text = readFileSync(file, "utf8");
  expect(text).toContain("Generated by Friday at every start");
  expect(text).toContain("## Members");
  expect(text).toMatch(/^\| researcher \| /m);
  expect(text).toContain("per channel: the teammate's prompt lists the locations");
  expect(text).not.toContain("none in this channel");
  expect(existsSync(`${file}.tmp`)).toBe(false);
  // An owner edit is overwritten at the next start.
  Bun.write(file, "edited");
  writeTeamFile(env.home);
  expect(readFileSync(file, "utf8")).toContain("## Members");
});
